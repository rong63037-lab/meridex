export function readingMinutes(article: Article): number {
  const chars = article.body.map((b) => (b.h ?? "") + (b.p ?? "") + (b.ul ?? []).join("") + (b.warn ?? "")).join("").length;
  return Math.max(1, Math.ceil(chars / 300));
}
