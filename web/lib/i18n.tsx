export type Lang = keyof typeof dict;
export type Copy = { [K in keyof (typeof dict)["zh"]]: string };

const ORDER: Lang[] = ["zh", "en", "ms"];

function htmlLang(lang: Lang): string {
  if (lang === "zh") return "zh-Hans";
  if (lang === "ms") return "ms";
  return "en";
}

const Ctx = createContext<{ lang: Lang; t: Copy; toggle: () => void; setLang: (lang: Lang) => void } | null>(null);

function mergeCopy(lang: Lang): Copy {
  const base = { ...(dict[lang] as Copy) };
  const overrides = currentOverrides();
  for (const key of Object.keys(base) as (keyof Copy)[]) {
    const hit = overrides[`${lang}.${key}`];
    if (typeof hit === "string") base[key] = hit;
  }
  return base;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("zh");
  const [rev, setRev] = useState(0);
  const setLang = (next: Lang) => {
    setLangState(next);
    localStorage.setItem("meridex.lang", next);
    document.documentElement.lang = htmlLang(next);
  };
  useEffect(() => {
    migrateClientStorage();
    const saved = localStorage.getItem("meridex.lang");
    if (saved === "en" || saved === "zh" || saved === "ms") setLang(saved);
    return startLiveContent();
  }, []);
  useEffect(() => subscribeLive(() => setRev((n) => n + 1)), []);
  const toggle = () => setLang(ORDER[(ORDER.indexOf(lang) + 1) % ORDER.length]);
  const t = mergeCopy(lang);
  void rev;
  return (
    <ToastProvider>
      <Ctx.Provider value={{ lang, t, toggle, setLang }}>{children}</Ctx.Provider>
    </ToastProvider>
  );
}

