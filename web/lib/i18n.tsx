export function reasonText(lang: Lang, code: string): string {
  const custom = currentOverrides()[`reason.${lang}.${code}`];
  if (custom) return custom;
  const known = reasons[lang][code];
  if (known) return known;
  if (/^[A-Z0-9_:-]+$/.test(code)) return reasons[lang].REQUEST_FAILED;
  return code;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("i18n");
  return ctx;
}

