export const accountBundles = { zh, en, ms };

export type AccountCopy = typeof en;

export function accountCopy(lang: string): AccountCopy {
  const base = lang === "en" ? en : lang === "ms" ? ms : zh;
  return applyCopy("account.", lang, base);
}

export function maskEmail(email: string): string {
  const [name, host] = email.split("@");
  if (!name || !host) return email;
  return `${name.slice(0, 1)}***@${host}`;
}
